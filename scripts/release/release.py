"""A release's files, from what the release workflow built (docs/specs/packaging.md "Releasing").

    python scripts/release/release.py check-version vX.Y.Z      the tag must match the runtime's __version__
    python scripts/release/release.py protocol                  the runtime's PROTOCOL
    python scripts/release/release.py manifest VERSION RUNNER SANDBOX > release.json
    python scripts/release/release.py notes VERSION > notes.md
    python scripts/release/release.py formula VERSION SHA256SUMS > doppel-runtime.rb

Standard library only: it runs before anything is installed.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPO = "summationai/doppel-runtime"
PLATFORMS = [("darwin", "arm64"), ("darwin", "amd64"), ("linux", "arm64"), ("linux", "amd64")]
VERSION = re.compile(r"^\d+\.\d+\.\d+$")


def runtime_version() -> str:
    text = (ROOT / "src/control-plane/doppel_control_plane/__init__.py").read_text()
    return re.search(r'^__version__ = "([^"]+)"', text, re.M).group(1)


def protocol() -> int:
    text = (ROOT / "src/control-plane/doppel_control_plane/bff.py").read_text()
    return int(re.search(r"^PROTOCOL = (\d+)", text, re.M).group(1))


def check_version(tag: str) -> str:
    version = tag.removeprefix("v")
    if not VERSION.match(version):
        raise SystemExit(f"{tag}: a release tag is vX.Y.Z")
    if version != runtime_version():
        raise SystemExit(f"{tag} doesn't match __version__ {runtime_version()!r}: bump it in a commit, then tag that")
    return version


def manifest(version: str, runner: str, sandbox: str) -> dict:
    for name, ref in (("runner", runner), ("sandbox", sandbox)):
        if "@sha256:" not in ref:
            raise SystemExit(f"the {name} image must be pinned by digest: {ref}")
    return {"version": version, "protocol": protocol(), "runner_image": runner, "sandbox_image": sandbox}


def notes(version: str) -> str:
    return f"""doppel-runtime {version}: a Doppelwerk review runner, run in Docker (26 or later).

Install, or pair a new runner (the code: Doppelwerk → Runners → Add a runner):

```sh
brew install summationai/tap/doppel-runtime          # Mac
curl -fsSL https://github.com/{REPO}/releases/latest/download/install.sh | sh   # Linux, or a Mac without Homebrew
doppel-runtime pair <code> --bff https://doppelwerk.ac0.app
```

Update a runner: `doppel-runtime update`.

Speaks runtime protocol {protocol()} with Doppelwerk (docs/specs/bff-split.md §2b).
"""


def sums(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            out[parts[1].lstrip("*")] = parts[0]
    return out


def formula(version: str, sums_file: Path) -> str:
    sha = sums(sums_file)
    missing = [f"doppel-runtime_{o}_{a}" for o, a in PLATFORMS if f"doppel-runtime_{o}_{a}" not in sha]
    if missing:
        raise SystemExit(f"SHA256SUMS is missing {', '.join(missing)}")

    def block(os_: str, arch: str) -> str:
        asset = f"doppel-runtime_{os_}_{arch}"
        url = f"https://github.com/{REPO}/releases/download/v#{{version}}/{asset}"
        return f'      url "{url}"\n      sha256 "{sha[asset]}"'

    return f"""# Generated by doppel-runtime's release workflow (scripts/release/release.py): don't edit by hand.
class DoppelRuntime < Formula
  desc "Run a Doppelwerk review runner in Docker"
  homepage "https://github.com/{REPO}"
  version "{version}"

  on_macos do
    on_arm do
{block("darwin", "arm64")}
    end
    on_intel do
{block("darwin", "amd64")}
    end
  end

  on_linux do
    on_arm do
{block("linux", "arm64")}
    end
    on_intel do
{block("linux", "amd64")}
    end
  end

  def install
    bin.install Dir["doppel-runtime_*"].first => "doppel-runtime"
  end

  def caveats
    <<~EOS
      A runner runs in Docker 26 or later. Pair one with the code from Doppelwerk (Runners → Add a runner):
        doppel-runtime pair <code> --bff https://doppelwerk.ac0.app
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/doppel-runtime version")
  end
end
"""


def main(argv: list[str]) -> int:
    match argv:
        case ["check-version", tag]:
            print(check_version(tag))
        case ["protocol"]:
            print(protocol())
        case ["manifest", version, runner, sandbox]:
            print(json.dumps(manifest(version, runner, sandbox), indent=2))
        case ["notes", version]:
            print(notes(version), end="")
        case ["formula", version, sums_file]:
            print(formula(version, Path(sums_file)), end="")
        case _:
            print(__doc__, file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
